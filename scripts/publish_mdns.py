#!/usr/bin/env python3
"""Write the avahi service file that lets the app find this device on Wi-Fi.

Generated rather than shipped static because it carries the device ID, and the
ID is a property of this particular board. Without it the app's only handle on a
device found over Wi-Fi is its service name ("SensorDyme on <hostname>"), which
changes if the hostname is edited and cannot be matched against the same device
seen over Bluetooth — so one Pi shows up as two.

Run by setup_pi.sh. Safe to re-run: the ID is stable, so the output is too.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from core.identity import device_id  # noqa: E402

DEFAULT_PATH = Path("/etc/avahi/services/sensordyme.service")

TEMPLATE = """<?xml version="1.0" standalone='no'?><!--*-nxml-*-->
<!DOCTYPE service-group SYSTEM "avahi-service.dtd">
<!--
  mDNS advertisement for the SensorDyme device dashboard.
  GENERATED by scripts/publish_mdns.py - edit that, not this file.

  The iOS app browses _sensordyme._tcp to find the device on the local network,
  so nobody types an IP address. The id= record is this device's stable
  identity: it is what lets the app tell "the same device at a new address"
  apart from "a second device".
-->
<service-group>
  <name replace-wildcards="yes">SensorDyme on %h</name>
  <service>
    <type>_sensordyme._tcp</type>
    <port>8899</port>
    <txt-record>path=/stream</txt-record>
    <txt-record>version=0.2</txt-record>
    <txt-record>id={device_id}</txt-record>
  </service>
</service-group>
"""


def render(identifier: str | None = None) -> str:
    return TEMPLATE.format(device_id=identifier or device_id())


def main() -> int:
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_PATH
    identifier = device_id()
    try:
        target.write_text(render(identifier))
    except PermissionError:
        print(f"error: need root to write {target}", file=sys.stderr)
        return 1
    print(f"advertising {identifier} at {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
