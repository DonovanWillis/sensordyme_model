#!/usr/bin/env python3
"""Build an ISOLATED development config: a device's config.yaml + one overlay, written elsewhere (M13).

    python dev_config.py --install-dir /home/$U/sensordyme \\
        --overlay ../../deploy/dev/reference_decoder.overlay.yaml --out ~/hwval/dev/config.reference.yaml

Reads <install-dir>/config.yaml (or this checkout's config.yaml when there is
none), deep-merges the overlay onto a copy, validates the result with
core/config_schema.py (any error: nothing is written), prints every key that
differs from the base, and writes the merged copy to --out with a header saying
what it is. It refuses an --out inside the installed tree and never touches the
installed config, the service or the model. Nothing selects the written file
unless a command names it (`main.py --config <file>`).
"""

from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import hwv_common as hc  # noqa: E402

DEFAULT_OVERLAY = hc.REPO_ROOT / "deploy" / "dev" / "reference_decoder.overlay.yaml"


def deep_merge(base: Any, overlay: Any) -> Any:
    """`overlay` onto a copy of `base`: mappings merge key by key, anything else replaces."""
    if isinstance(base, dict) and isinstance(overlay, dict):
        out = copy.deepcopy(base)
        for key, value in overlay.items():
            out[key] = deep_merge(base.get(key), value) if key in base else copy.deepcopy(value)
        return out
    return copy.deepcopy(overlay)


def differences(a: Any, b: Any, prefix: str = "") -> list[tuple[str, Any, Any]]:
    """Every dotted key whose value differs between `a` and `b`."""
    if isinstance(a, dict) and isinstance(b, dict):
        out = []
        for key in sorted(set(a) | set(b), key=str):
            out += differences(a.get(key), b.get(key), f"{prefix}{key}.")
        return out
    return [] if a == b else [(prefix.rstrip("."), a, b)]


def build(base: dict, overlay: dict) -> tuple[dict, list[tuple[str, Any, Any]], list[str], list[str]]:
    sys.path.insert(0, str(hc.REPO_ROOT))
    from core.config_schema import validate

    merged = deep_merge(base, overlay)
    errors, warnings = validate(merged)
    return merged, differences(base, merged), errors, warnings


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--install-dir", type=Path, default=hc.DEFAULT_INSTALL_DIR)
    p.add_argument("--overlay", type=Path, default=DEFAULT_OVERLAY)
    p.add_argument("--out", type=Path, required=True)
    args = p.parse_args(argv)

    base_path = args.install_dir / "config.yaml"
    if not base_path.exists():
        base_path = hc.REPO_ROOT / "config.yaml"
    ok, why = hc.ensure_outside(args.out, args.install_dir)
    if not ok:
        print(f"REFUSED: {why}", file=sys.stderr)
        return 2
    if args.out.resolve() == base_path.resolve():
        print("REFUSED: --out is the base config itself", file=sys.stderr)
        return 2
    base = yaml.safe_load(base_path.read_text()) or {}
    overlay = yaml.safe_load(args.overlay.read_text()) or {}
    merged, diff, errors, warnings = build(base, overlay)
    for w in warnings:
        print(f"warning: {w}")
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        print("REFUSED: the merged config does not validate; nothing written", file=sys.stderr)
        return 1
    print(f"base     {base_path}")
    print(f"overlay  {args.overlay}")
    for key, old, new in diff:
        print(f"  {key}: {old!r} -> {new!r}")
    if not diff:
        print("  (no difference: the base already has every overlay value)")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    header = (f"# DEVELOPMENT CONFIG -- NOT INSTALLED. Generated by scripts/hw_validation/dev_config.py from\n"
              f"#   {base_path}\n#   + {args.overlay}\n"
              f"# Differences from the base: {', '.join(k for k, _, _ in diff) or 'none'}.\n"
              f"# Used only by a command that names it (main.py --config <this file>).\n")
    args.out.write_text(header + yaml.safe_dump(merged, sort_keys=False))
    print(f"written  {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
