#!/usr/bin/env python3
"""Write tests/local_access_vectors.json: sd-local-v1 vectors for the Swift client.

The phone (ios/Sources/LocalAccess*.swift) must build the SAME canonical
strings, verify the device's signatures and produce signatures the device
verifies. ECDSA signatures are randomised, so the vectors carry a valid
signature to verify (not one to reproduce); everything else is exact.

TEST KEYS ONLY: the scalars below are fixed, public, and used nowhere else.

    .venv/bin/python scripts/local_access_vectors.py            # rewrite the file
    .venv/bin/python scripts/local_access_vectors.py --check    # exit 1 if it would change
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from core import local_auth as la
from services import ble_pop
from sim.local_client import PhoneKey

OUT = Path(__file__).resolve().parents[1] / "tests" / "local_access_vectors.json"
PHONE_SCALAR = int("11" * 32, 16)
DEVICE_SCALAR = int("22" * 32, 16)


def build(existing: dict | None = None) -> dict:
    ec, *_ = la._ec()
    phone = PhoneKey.from_scalar(PHONE_SCALAR)
    device = la.DeviceIdentity(ec.derive_private_key(DEVICE_SCALAR, ec.SECP256R1()))
    device_id = "SD-1A2B3C4D"
    challenge = "0123456789abcdef0123456789abcdef"
    body = b'{"action":"stop","confirm":true}'
    request = la.request_message(device_id, phone.client_id, challenge, "POST", "/api/protection", body)
    client_nonce = "fedcba9876543210fedcba9876543210"
    session = "c2Vzc2lvbi10b2tlbi1mb3ItdGVzdHMtb25seS0xMjM0"
    session_msg = la.session_message(device_id, phone.client_id, challenge, client_nonce, session, 900)

    # Signatures: keep the stored ones while they still verify (stable file).
    old = existing or {}
    phone_sig = la.b64u_decode(old.get("request", {}).get("phone_signature"), 64)
    if phone_sig is None or not la.verify_signature(phone.public_key, request, phone_sig):
        phone_sig = phone.sign(request)
    device_sig = la.b64u_decode(old.get("session", {}).get("device_signature"), 64)
    if device_sig is None or not la.verify_signature(device.public_key, session_msg, device_sig):
        device_sig = device.sign(session_msg)

    # BLE enrolment inside a proven PoP session (deterministic: fixed nonces and IVs).
    code, na, nd = "7K3M9Q2W4X8Z", bytes(range(16)), bytes(range(16, 32))
    keys = ble_pop.session_keys(ble_pop.derive_code_key(code, device_id), device_id, na, nd)
    enroll_iv, enrolled_iv = bytes(range(32, 44)), bytes(range(44, 56))
    enroll_ct = ble_pop.seal_enrollment(keys, la.b64u(phone.public_key), "Test iPhone", enroll_iv)
    reply = {"client_id": phone.client_id, "device_id": device_id, "device_public_key": la.b64u(device.public_key)}
    enrolled_ct = ble_pop.seal_enrolled(keys, reply, enrolled_iv)

    return {
        "contract": la.CONTRACT,
        "note": "TEST KEYS ONLY. Generated by scripts/local_access_vectors.py; Swift embeds this file verbatim.",
        "phone": {"scalar_hex": f"{PHONE_SCALAR:064x}", "public_key": la.b64u(phone.public_key),
                  "client_id": phone.client_id},
        "device": {"scalar_hex": f"{DEVICE_SCALAR:064x}", "public_key": la.b64u(device.public_key),
                   "key_fp": device.fingerprint, "device_id": device_id},
        "request": {"challenge": challenge, "method": "POST", "path": "/api/protection",
                    "body": body.decode(), "body_sha256": hashlib.sha256(body).hexdigest(),
                    "message": request.decode(), "phone_signature": la.b64u(phone_sig),
                    "header": la.format_header(phone.client_id, challenge, phone_sig)},
        "session": {"challenge": challenge, "client_nonce": client_nonce, "session": session,
                    "expires_in_s": 900, "message": session_msg.decode(), "device_signature": la.b64u(device_sig)},
        "ble_enroll": {"setup_code": code, "device_id": device_id, "na": base64.b64encode(na).decode(),
                       "nd": base64.b64encode(nd).decode(), "name": "Test iPhone",
                       "enroll_iv": base64.b64encode(enroll_iv).decode(),
                       "enroll_plaintext": ble_pop._canonical({"name": "Test iPhone",
                                                               "public_key": la.b64u(phone.public_key)}).decode(),
                       "enroll_ct": base64.b64encode(enroll_ct).decode(),
                       "enrolled_iv": base64.b64encode(enrolled_iv).decode(),
                       "enrolled_plaintext": ble_pop._canonical(reply).decode(),
                       "enrolled_ct": base64.b64encode(enrolled_ct).decode()},
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    existing = json.loads(OUT.read_text()) if OUT.exists() else None
    text = json.dumps(build(existing), indent=2, sort_keys=True) + "\n"
    if args.check:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
