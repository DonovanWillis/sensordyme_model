#!/usr/bin/env python3
"""Add Swift files to SensorDyme.xcodeproj without regenerating it.

    python scripts/add_ios_file.py EventDetailView.swift ZoneEditorView.swift
    python scripts/add_ios_file.py --sync        # add every file not yet listed

The project is generated by XcodeGen, which bakes an explicit file list into
project.pbxproj. A Swift file created afterwards compiles fine on its own and is
invisible to the build — the failure is `cannot find 'X' in scope`, which reads
like a code error rather than a project one. `xcodegen generate` fixes it
properly; this exists for when xcodegen isn't installed.

Each file needs an entry in FOUR places. Miss one and the file is either not
compiled or not visible.
"""

from __future__ import annotations

import argparse
import re
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PBXPROJ = ROOT / "ios" / "SensorDyme.xcodeproj" / "project.pbxproj"
SOURCES = ROOT / "ios" / "Sources"


def add(text: str, name: str) -> tuple[str, bool]:
    """Insert one file's four entries. Returns (text, added)."""
    if f"/* {name} " in text or f"/* {name} */" in text:
        return text, False

    build_id, file_id = uuid.uuid4().hex[:24].upper(), uuid.uuid4().hex[:24].upper()
    if build_id in text or file_id in text:
        raise SystemExit("uuid collision; run again")

    # Anchor on any existing Swift file rather than a named one, so this keeps
    # working when the project's contents change.
    anchors = {
        "build": re.search(r"^\t\t\w{24} /\* \w+\.swift in Sources \*/ = .*$", text, re.M),
        "ref": re.search(r"^\t\t\w{24} /\* \w+\.swift \*/ = \{isa = PBXFileReference.*$", text, re.M),
        "child": re.search(r"^\t\t\t\t\w{24} /\* \w+\.swift \*/,$", text, re.M),
        "src": re.search(r"^\t\t\t\t\w{24} /\* \w+\.swift in Sources \*/,$", text, re.M),
    }
    missing = [key for key, match in anchors.items() if match is None]
    if missing:
        raise SystemExit(f"could not find anchors in project.pbxproj: {missing}")

    additions = {
        "build": f"\n\t\t{build_id} /* {name} in Sources */ = {{isa = PBXBuildFile; fileRef = {file_id} /* {name} */; }};",
        "ref": f"\n\t\t{file_id} /* {name} */ = {{isa = PBXFileReference; lastKnownFileType = sourcecode.swift; path = {name}; sourceTree = \"<group>\"; }};",
        "child": f"\n\t\t\t\t{file_id} /* {name} */,",
        "src": f"\n\t\t\t\t{build_id} /* {name} in Sources */,",
    }
    for key, match in anchors.items():
        text = text.replace(match.group(0), match.group(0) + additions[key], 1)
    return text, True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("files", nargs="*", help="Swift filenames under ios/Sources")
    parser.add_argument("--sync", action="store_true",
                        help="add every file in ios/Sources not already listed")
    args = parser.parse_args()

    if not PBXPROJ.exists():
        raise SystemExit(f"no project at {PBXPROJ} — run `xcodegen generate` in ios/ first")

    text = PBXPROJ.read_text()
    names = args.files
    if args.sync:
        names = sorted(p.name for p in SOURCES.glob("*.swift"))
    if not names:
        parser.error("give filenames, or --sync")

    # One backup per run, so a bad edit is always recoverable.
    backup = PBXPROJ.with_suffix(".pbxproj.bak")
    backup.write_text(text)

    added = []
    for name in names:
        if not (SOURCES / name).exists():
            print(f"  ! {name} does not exist in ios/Sources — skipped")
            continue
        text, did = add(text, name)
        if did:
            added.append(name)

    if not added:
        print("nothing to add; every file is already in the project")
        return 0

    PBXPROJ.write_text(text)
    for name in added:
        print(f"  + {name}")
    print(f"\nadded {len(added)} file(s); backup at {backup.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
